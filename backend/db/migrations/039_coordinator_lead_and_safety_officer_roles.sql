-- 039_coordinator_lead_and_safety_officer_roles.sql
-- SCRUM-507: add the two roles to the database's list of valid roles
--
-- Part of SCRUM-485 "Add the Event Coordinator Lead and Safety Officer Roles".
-- Run this once in the Supabase SQL Editor, after 007_user_roles.sql (which
-- defines user_role). Safe to re-run.
--
-- AC5 asks for the new roles to be accepted "wherever roles are checked,
-- including the database's list of valid roles". That list is the user_role
-- enum, the type of profiles.role. This adds exactly two values to it and
-- nothing else:
--
--   'event_coordinator_lead'   Event Coordinator Lead
--   'safety_officer'           Safety Officer
--
-- Existing values and rows are untouched (AC6).
--
--
-- Why a new migration, not an edit to 007:
--
--   * Migrations are append-only. 001's header states the rule: additions go
--     in a new numbered migration rather than an edit.
--   * 007 says how to do exactly this: "To add a value later:  alter type
--     user_role add value 'x';".
--   * Editing 007 would change nothing where it matters. It creates the enum
--     only `if not exists`, and the live database already had the enum before
--     007 was written, so 007's create statement never ran there. A value
--     added to 007's list would never reach that database.
--
-- `if not exists` on each statement, so a second run is a no-op rather than an
-- error. The precedent is on the live database already: it holds a sixth value,
-- technical_support, that 007 does not declare, so `add value` has been applied
-- there before, successfully.
--
--
-- The spelling: lowercase snake_case, like every live value (event_organiser,
-- event_coordinator, venue_staff, technical_support_staff, attendee). The names
-- in words are AC1's, "Event Coordinator Lead" and "Safety Officer".
--
-- Neither can be mistaken for event_coordinator, although one begins with it.
-- Nothing compares roles by prefix:
--   * requireRole uses allowed.includes(req.user.role), an exact match;
--   * ProtectedRoute compares whole normalised keys, and EVENT_COORDINATOR_LEAD
--     is not EVENT_COORDINATOR;
--   * the SQL that checks a role uses =, as in p.role = 'event_coordinator'.
-- So a Lead passes no Event Coordinator gate. That is deliberate: this story
-- creates the roles, and SCRUM-486, 487, 489 and 490 grant each one what it
-- may do (docs/test-cases/SCRUM-485.md, "The Lead inherits nothing").
--
--
-- Nothing in this file uses the new values. Postgres refuses to use an enum
-- value in the transaction that added it, and the SQL Editor runs a script as
-- one transaction, so an insert or a function naming 'safety_officer' here
-- would fail. 027 makes the same point for booking_status.
--
--
-- What this migration deliberately does not do:
--
--   * Remove anything. technical_support stays in the enum. It is dead: a query
--     on 10 October found no profile using it. Every Technical Support user
--     holds technical_support_staff, which is the value the code checks, so
--     those routes work. Recorded here so the next reader does not take it for
--     a broken role, as docs/SCRUM-327.md and the headers of 014 and 015 did.
--     It is not dropped because Postgres cannot drop an enum value without
--     recreating the type, and recreating user_role would mean redefining
--     every function that names a role, for no change in behaviour.
--
--   * Create any profiles row. Test accounts for the two roles are SCRUM-511's
--     (AC7), and could not be made here anyway, for the transaction reason
--     above.
--
--   * Grant either role anything. No function, gate or policy changes.
--
--   * Notify PostgREST. 027 and 028, which change booking_status, do not
--     either: the reload matters for new functions, and this adds none.

alter type user_role add value if not exists 'event_coordinator_lead';
alter type user_role add value if not exists 'safety_officer';
