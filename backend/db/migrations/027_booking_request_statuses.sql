-- 027_booking_request_statuses.sql
-- SCRUM-250: Extend booking storage and status definitions
--
-- Part of SCRUM-243 "Submit a Venue Booking Request". Run this once in the
-- Supabase SQL Editor, after 011_venue_blocks.sql (which defines
-- booking_status). Safe to re-run.
--
-- A booking was only ever an approved hold on a venue, so booking_status had
-- three values. A venue booking *request* also needs to be waiting for a
-- decision, turned down, or taken back by its Coordinator. This adds exactly
-- those three values and nothing else:
--
--   'pending'    submitted by a Coordinator; Venue Staff have not decided
--   'rejected'   Venue Staff declined it
--   'withdrawn'  the Coordinator took it back while it was still pending
--
-- Existing values and rows are untouched, and so is the column's default,
-- which stays 'approved' here. Changing it to 'pending' is SCRUM-251.
--
-- Why nothing but the enum: a request already has somewhere to put what it
-- needs -- venue_id, event_request_id, starts_at, ends_at, created_at. The
-- fields only a request carries (layout, requirements, suitability result,
-- setup notes, who requested) belong to the submit step that writes them.
--
-- The new values sit AFTER the existing ones, because `add value` appends and
-- backend/src/domain/bookingStatus.js mirrors the enum in declared order.
--
-- Nothing in this file uses the new values. Postgres refuses to use an enum
-- value in the transaction that added it, and the SQL Editor runs a script as
-- one transaction.
--
-- Effect on existing code, all deliberate:
--   * idx_bookings_venue_approved, venue_block_booking_conflicts() and
--     create_venue_block only look at status = 'approved', so a pending,
--     rejected or withdrawn row never conflicts with a block.
--   * flag_bookings_for_block only flags 'approved' rows.
--   * The venue calendar reads an allow-list (approved, flagged_for_review),
--     so the new statuses do not appear on it.

alter type booking_status add value if not exists 'pending';
alter type booking_status add value if not exists 'rejected';
alter type booking_status add value if not exists 'withdrawn';
